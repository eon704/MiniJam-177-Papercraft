public enum TerrainType
{
    Empty,
    Default,
    Start,
    End,
    Water,
    Stone,
    Fire,
    Volcano,
    Lava,
    Ice,
    /// <summary>Кувшинка: островок на воде. Журавль и лягушка встают, лодка причаливает; тонет (становится водой), когда с неё уходят.</summary>
    LilyPad,
    /// <summary>Песок (Океан): суша, на которую приливом наступает вода.</summary>
    Sand,
    /// <summary>Пол из короба (Пещера): короб, столкнутый в провал, заполняет его. Суша для всех, не рушится.</summary>
    BoxFloor,
    /// <summary>Плита (Пещера): пока на ней журавль, лягушка или короб, все ворота открыты.</summary>
    Plate,
    /// <summary>Ворота (Пещера): закрыты — стена для всех форм; открыты — обычная клетка.</summary>
    Gate,
    /// <summary>Тонкий лёд (Снега): держит все формы; под лягушкой трескается (становится треснувшим льдом).</summary>
    ThinIce,
    /// <summary>Бамбук (Снега): стена для всех форм; сюрикен срезает его на пути, клетка становится обычной.</summary>
    Bamboo,
    /// <summary>Зыбучий песок (Пустыня): стоящий на нём не может сменить форму; лягушка тонет сразу; бабочку держит.</summary>
    Quicksand,
    /// <summary>Треснувший лёд (Снега): тонкий лёд после прыжка лягушки. Держит все формы; когда с него уходят, становится водой.</summary>
    CrackedIce
}